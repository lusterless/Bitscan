def fixture(name: str, *, canary: str = "/nonexistent", port: int = 9) -> bytes:
    """Fixture bytes with the manifest placeholders substituted."""
    raw = (BT / name).read_bytes()
    return raw.replace(b"@@CANARY@@", canary.encode()).replace(
        b"@@PORT@@", str(port).encode()
    )


def fixtures_in(folder: str) -> list[str]:
    return sorted(f for f in FIXTURES if f.startswith(folder + "/"))


# --- generated canonical files ---------------------------------------------

HEAD = (
    '<?xml version="1.0" encoding="UTF-8"?>\n'
    '<Policy formatVersion="1.0">\n'
    "  <PolicyName>Generated policy</PolicyName>\n"
    "  <PolicyDescription>Generated by the tester.</PolicyDescription>\n"
    "  <PolicyStatus>enabled</PolicyStatus>\n"
    "  <Family>\n"
    "    <FamilyName>Bitscan Test Family</FamilyName>\n"
    "  </Family>\n"
    "  <PluginsGroups>\n"
)
TAIL = "  </PluginsGroups>\n</Policy>\n"


def plugin_xml(i: int, execute: str = "cat /etc/hostname") -> str:
    return (
        "    <Plugin>\n"
        f"      <PluginName>{i}.1 - Generated check {i}</PluginName>\n"
        f"      <PluginDescription>Check {i}.</PluginDescription>\n"
        f"      <PluginId>{uuid.UUID(int=i + 1)}</PluginId>\n"
        f'      <Execute timeout="30"><![CDATA[{execute}]]></Execute>\n'
        "      <Operator>not_empty</Operator>\n"
        "      <ExpectedResult></ExpectedResult>\n"
        "    </Plugin>\n"
    )


def canonical(plugins: int = 1, *, pad_to: int | None = None) -> bytes:
    """A canonical file with ``plugins`` plugins; ``pad_to`` pads it to exactly
    that many bytes with one comment after the declaration."""
    body = "".join(plugin_xml(i) for i in range(1, plugins + 1))
    text = HEAD + body + TAIL
    data = text.encode("utf-8")
    if pad_to is None:
        return data
    decl, rest = data.split(b"\n", 1)
    overhead = len(data) + len(b"<!---->\n")
    assert pad_to >= overhead, "target smaller than the file"
    comment = b"<!--" + b"a" * (pad_to - overhead) + b"-->\n"
    out = decl + b"\n" + comment + rest
    assert len(out) == pad_to
    return out


# --- start-tag lines computed from the text (not from the parser) -------------


def start_tags(text: str) -> list[tuple[str, int]]:
    """(name, line) of every start tag in document order, skipping comments,
    CDATA sections, PIs, declarations and end tags. String scanning only."""
    out: list[tuple[str, int]] = []
    i = 0
    n = len(text)
    while True:
        j = text.find("<", i)
        if j < 0 or j + 1 >= n:
            return out
        if text.startswith("<!--", j):
            i = text.index("-->", j) + 3
        elif text.startswith("<![CDATA[", j):
            i = text.index("]]>", j) + 3
        elif text[j + 1] in "?!":
            i = text.index(">", j) + 1
        elif text[j + 1] == "/":
            i = text.index(">", j) + 1
        else:
            k = j + 1
            while k < n and text[k] not in " \t\r\n/>":
                k += 1
            out.append((text[j + 1 : k], text.count("\n", 0, j) + 1))
            i = k


# --- side-effect recorder (audit hook, installed once) -----------------------

_WATCHED_PREFIXES = (
    "open",
    "socket.",
    "urllib.",
    "http.",
    "subprocess.",
    "os.system",
    "os.exec",
    "os.spawn",
    "os.posix_spawn",
    "os.startfile",
    "os.listdir",
    "os.scandir",
    "os.remove",
    "os.rename",
    "shutil.",
    "ctypes.",
    "webbrowser.",
    "ftplib.",
)


@dataclass
class _Recorder:
    active: bool = False
    thread: int = 0
    events: list[tuple[str, str]] = field(default_factory=list)


_REC = _Recorder()


def _hook(event: str, args: tuple[Any, ...]) -> None:
    rec = _REC
    if not rec.active or threading.get_ident() != rec.thread:
        return
    if event.startswith(_WATCHED_PREFIXES):
        rec.events.append((event, repr(args)[:200]))


sys.addaudithook(_hook)


@contextmanager
def no_side_effects() -> Iterator[list[tuple[str, str]]]:
    """Record file, network, process and ctypes audit events of this thread."""
    assert not _REC.active, "recorder is not re-entrant"
    _REC.events = []
    _REC.thread = threading.get_ident()
    _REC.active = True
    try:
        yield _REC.events
    finally:
        _REC.active = False


@contextmanager
def listener() -> Iterator[tuple[int, socket.socket]]:
    """A local TCP listener; the caller checks ``connected`` afterwards."""
    srv = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    srv.bind(("127.0.0.1", 0))
    srv.listen(8)
    srv.setblocking(False)
    try:
        yield srv.getsockname()[1], srv
    finally:
        srv.close()


def connected(srv: socket.socket, wait: float = 0.3) -> bool:
    readable, _, _ = select.select([srv], [], [], wait)
    return bool(readable)
