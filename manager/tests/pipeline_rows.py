"""Shared helpers for the TASK-154 pipeline suites (tester-m7-154; TP-M7-14).

No product code here. Files are generated as text from the SR §2 shape with
fresh names and plugin ids per test, so tests sharing a database never meet
through BIT007 or BIT015. Every read of the results is done as owner
(``bitscan_migrate`` + ``SET ROLE bitscan_owner``); the code under test runs
as ``bitscan_app`` through ``AppDatabase``.
"""

