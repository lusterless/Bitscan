class FixedClock:
    def __init__(self, at: datetime = T1) -> None:
        self.at = at

    def now(self) -> datetime:
        return self.at


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


@dataclass(frozen=True)
class P:
    """One generated plugin."""

    execute: str = "cat /etc/hostname"
    uuid: UUID | None = None
    operator: str = "not_empty"
    expected: str = ""
    name: str | None = None


def bit(
    name: str | None = None,
    plugins: Sequence[P] | None = None,
    *,
    status: str = "enabled",
    family: str = "Pipeline Test Family",
    format_version: str = "1.0",
) -> tuple[bytes, list[UUID]]:
    """A file and its plugin ids. Line numbers: PolicyName 3, PolicyStatus 5,
    plugin n starts at 10 + 8 (n - 1), its Execute at that + 4."""
    name = name if name is not None else f"Pipeline {tag()}"
    plugins = list(plugins) if plugins is not None else [P()]
    ids: list[UUID] = []
    body = []
    for i, p in enumerate(plugins, start=1):
        u = p.uuid or uuid4()
        ids.append(u)
        body.append(
            "    <Plugin>\n"
            f"      <PluginName>{p.name or f'{i}.1 - Check {i}'}</PluginName>\n"
            f"      <PluginDescription>Check {i}.</PluginDescription>\n"
            f"      <PluginId>{u}</PluginId>\n"
            f'      <Execute timeout="30"><![CDATA[{p.execute}]]></Execute>\n'
            f"      <Operator>{p.operator}</Operator>\n"
            f"      <ExpectedResult>{p.expected}</ExpectedResult>\n"
            "    </Plugin>\n"
        )
    text = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        f'<Policy formatVersion="{format_version}">\n'
        f"  <PolicyName>{name}</PolicyName>\n"
        "  <PolicyDescription>Generated by tester-m7-154.</PolicyDescription>\n"
        f"  <PolicyStatus>{status}</PolicyStatus>\n"
        "  <Family>\n"
        f"    <FamilyName>{family}</FamilyName>\n"
        "  </Family>\n"
        "  <PluginsGroups>\n" + "".join(body) + "  </PluginsGroups>\n</Policy>\n"
    )
    return text.encode("utf-8"), ids


def server_file(
    data: bytes | None, path: str | None = None, digest: str = ""
) -> FileInput:
    path = path or f"p-{tag()}.bit"
    d = digest or sha(data or b"")
    return FileInput(data, d, path, Target("server", path, d))


def upload_file(data: bytes, client_name: str = "client.bit") -> FileInput:
    d = sha(data)
    return FileInput(data, d, client_name, Target("upload", None, d))


def metric(name: str, labels: dict[str, str]) -> float:
    v = REGISTRY.get_sample_value(name, labels)
    return 0.0 if v is None else float(v)


def counters() -> dict[str, float]:
    out = {f"alert:{k}": metric("bitscan_alerts_total", {"kind": k}) for k in KINDS}
    for m in MODES:
        out[f"fail:{m}"] = metric("bitscan_import_failures_total", {"mode": m})
    return out


def _max(conn: Any, table: str, key: str) -> int:
    from psycopg import sql

    query = sql.SQL("SELECT coalesce(max({k}), 0) FROM {t}").format(
        k=sql.Identifier(key), t=sql.Identifier(table)
    )
    row = conn.execute(query).fetchone()
    assert row is not None
    return int(row[0])


@dataclass
class Snap:
    """Everything an import may change, taken before it."""

    catalog: dict[str, str]
    import_id: int
    audit_id: int
    counters: dict[str, float]


def snap(server: PgServer) -> Snap:
    with owner(server) as c:
        return Snap(
            catalog_checksums(c),
            _max(c, "bit_import", "import_id"),
            _max(c, "audit_log", "audit_id"),
            counters(),
        )


def imports_since(server: PgServer, s: Snap) -> list[dict[str, Any]]:
    with owner(server) as c:
        cur = c.execute(
            "SELECT import_id, file_name, file_sha256, policy_version, mode, outcome,"
            " plugins_added, plugins_updated, plugins_retired, errors::text AS errors,"
            " imported_by, imported_at, xmin::text AS xmin FROM bit_import"
            " WHERE import_id > %s ORDER BY import_id",
            (s.import_id,),
        )
        names = [d.name for d in cur.description or []]
        rows = [dict(zip(names, r, strict=True)) for r in cur.fetchall()]
    for r in rows:
        r["errors"] = json.loads(r["errors"])
    return rows


def audits_since(server: PgServer, s: Snap) -> list[dict[str, Any]]:
    with owner(server) as c:
        cur = c.execute(
            "SELECT audit_id, actor, action, target, detail::text AS detail,"
            " xmin::text AS xmin FROM audit_log WHERE audit_id > %s ORDER BY audit_id",
            (s.audit_id,),
        )
        names = [d.name for d in cur.description or []]
        rows = [dict(zip(names, r, strict=True)) for r in cur.fetchall()]
    for r in rows:
        r["detail"] = json.loads(r["detail"]) if r["detail"] is not None else None
    return rows


def counter_delta(s: Snap) -> dict[str, float]:
    now = counters()
    return {k: now[k] - v for k, v in s.counters.items() if now[k] != v}


def catalog_now(server: PgServer) -> dict[str, str]:
    with owner(server) as c:
        return catalog_checksums(c)


def policy_row(server: PgServer, policy_id: int) -> dict[str, Any]:
    with owner(server) as c:
        cur = c.execute(
            "SELECT policy_id, policy_name, policy_status::text AS policy_status,"
            " file_status::text AS file_status, status_overridden, version,"
            " source_file, source_sha256, deleted_at, xmin::text AS xmin"
            " FROM policy WHERE policy_id = %s",
            (policy_id,),
        )
        row = cur.fetchone()
        assert row is not None
        return dict(zip([d.name for d in cur.description or []], row, strict=True))


def policy_by_name(server: PgServer, name: str) -> dict[str, Any] | None:
    with owner(server) as c:
        row = c.execute(
            "SELECT policy_id FROM policy WHERE policy_name = %s", (name,)
        ).fetchone()
    return None if row is None else policy_row(server, int(row[0]))


def members(server: PgServer, policy_id: int) -> list[tuple[UUID, str, str]]:
    """(uuid, execute, state) in sort_order."""
    with owner(server) as c:
        return [
            (UUID(str(u)), str(e), str(s))
            for u, e, s in c.execute(
                "SELECT pp.plugin_uuid, p.execute, p.state::text FROM policy_plugin pp"
                " JOIN plugin p USING (plugin_uuid) WHERE pp.policy_id = %s"
                " ORDER BY pp.sort_order",
                (policy_id,),
            ).fetchall()
        ]


def codes(errors: Iterable[dict[str, Any]]) -> list[str]:
    return [e["code"] for e in errors]


def bits_dir(tmp: Path) -> Path:
    (tmp / "uploaded").mkdir(exist_ok=True)
    return tmp
